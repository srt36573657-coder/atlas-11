/** 「왜 사?」 · 매매일지 그림(su-why.js 가 그린 svg)의 그림 뜻 — svg 이름 · 지금 물음 · 기록 수로 고름 */
export function whyMean(cls = '', cur = '', n = '') {
  if (/\bik-why\b/.test(cls)) return cur !== '' && cur != null ? PM.why : PM.whyDone;
  if (/\bik-journal\b/.test(cls)) return +n > 0 ? PM.journal : PM.journal0;
  if (/\bik-tally\b/.test(cls)) return PM.tally;
  if (/\bik-groups\b/.test(cls)) return PM.groups;
  return null;
}
