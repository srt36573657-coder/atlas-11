def lin(c): c /= 255; return c / 12.92 if c <= .04045 else ((c + .055) / 1.055) ** 2.4
def lum(h): h = h.lstrip('#'); r, g, b = (int(h[i:i + 2], 16) for i in (0, 2, 4)); return .2126 * lin(r) + .7152 * lin(g) + .0722 * lin(b)
def cr(a, b): x, y = lum(a), lum(b); return round((max(x, y) + .05) / (min(x, y) + .05), 1)
def name(hexc, L=None, C=None, hue=None):
    h = hexc.lstrip('#'); r, g, b = (int(h[i:i + 2], 16) / 255 for i in (0, 2, 4)); hh, ll, ss = colorsys.rgb_to_hls(r, g, b); d = hh * 360
    tone = '아주 짙은 ' if ll < .08 else '짙은 ' if ll < .22 else '' if ll < .6 else '옅은 ' if ll < .85 else '하얀 '
    if ss < .14 or (ll > .8 and ss < .3): base = '회색' if ll < .85 else '흰빛'
    elif 180 <= d < 215: base = '하늘색'
    elif 215 <= d < 250: base = '남색'
    elif 250 <= d < 280: base = '남보라'
    elif 280 <= d < 300: base = '보라'
    elif 300 <= d < 335: base = '자홍'
    elif d >= 335 or d < 15: base = '분홍빛 빨강'
    else: base = '다른 색'
    return (tone + base).strip()
