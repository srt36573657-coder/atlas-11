// 사고 팔기(주문 1125-0049 · 사장님 2026-11-25 00:40 · 00:49 「… 그 기준 날짜로 팔고 … 12프로 하락이면 자동으로 팔게 … 모든 거래는 종가 기준」)
//   정한 날 종가로 팖 · 100원에 산 것이 88원 이하로 마감하면 그날 팖 · 종가가 빠진 날은 건너뜀 · 아직이면 들고 있음 · 꾀 아닌 묶음은 셈 밖 · 실제 보기 셋
import test from 'node:test';
import assert from 'node:assert/strict';
import {sellOne, sellsOf, SELL_DAYS, SELL_CUT, SELL_RULE, KINDS, S36} from '../../scripts/atlas11/next/su21_settle.mjs';

const TD = ['2026-11-12', '2026-11-13', '2026-11-16', '2026-11-17', '2026-11-18', '2026-11-19', '2026-11-20'];

test('정한 날(3일째) 종가로 팖 — 올랐든 안 올랐든', () => {
  const px = {'2026-11-12': 10000, '2026-11-13': 10500, '2026-11-16': 9000, '2026-11-17': 9500, '2026-11-18': 12000};
  assert.deepEqual(sellOne(px, TD, 0, 10000, 3), ['d', '2026-11-17', 9500, 3]);
  const up = {...px, '2026-11-17': 11000};
  assert.deepEqual(sellOne(up, TD, 0, 10000, 3), ['d', '2026-11-17', 11000, 3]);
});

test('88원 줄 — 1만 원에 산 것이 8,800원 이하로 마감한 날 바로 팖 · 8,801원은 안 팖', () => {
  assert.equal(SELL_CUT, 88);
  const px = {'2026-11-12': 10000, '2026-11-13': 9500, '2026-11-16': 8800, '2026-11-17': 9900, '2026-11-18': 9900, '2026-11-19': 9900, '2026-11-20': 9900};
  assert.deepEqual(sellOne(px, TD, 0, 10000, 5), ['c', '2026-11-16', 8800, 2]);
  assert.deepEqual(sellOne({...px, '2026-11-16': 8801}, TD, 0, 10000, 5), ['d', '2026-11-19', 9900, 5]);
  // 정한 날에 88원 줄 밑이면 88원 줄로 셈(먼저 봄)
  assert.deepEqual(sellOne({...px, '2026-11-16': 9000, '2026-11-17': 8000}, TD, 0, 10000, 3), ['c', '2026-11-17', 8000, 3]);
  // 값이 커도 정확히(소수 셈 흔들림 없음) — 38,900원 → 줄 34,232원
  assert.deepEqual(sellOne({'2026-11-13': 34232}, TD, 0, 38900, 4), ['c', '2026-11-13', 34232, 1]);
  assert.deepEqual(sellOne({'2026-11-13': 34233}, TD, 0, 38900, 1), ['d', '2026-11-13', 34233, 1]);
});

test('종가가 빠진 날은 건너뜀 — 정한 날에 종가가 없으면 다음 장날 종가로', () => {
  const px = {'2026-11-12': 10000, '2026-11-13': 10100, '2026-11-16': 10200, '2026-11-18': 10400};
  assert.deepEqual(sellOne(px, TD, 0, 10000, 3), ['d', '2026-11-18', 10400, 4]);
});

test('아직 정한 날 전이면 들고 있음 — 가장 늦은 종가 · 산 날 뒤 종가가 없으면 산 값', () => {
  assert.deepEqual(sellOne({'2026-11-13': 10300, '2026-11-16': 10600}, TD.slice(0, 3), 0, 10000, 4), ['h', '2026-11-16', 10600, 2]);
  assert.deepEqual(sellOne({}, TD.slice(0, 1), 0, 10000, 4), ['h', '2026-11-12', 10000, 0]);
  assert.equal(sellOne({}, TD, null, 10000, 4), null);
});

test('파는 날 표(sell-v1) — 꾀 36 · 3일째 3 · 4일째 14 · 5일째 5 · 6일째 7 · 7일째 4 · 8일째 2 · 9일째 1 · 「강 건너 불 보기」(g09) 7일째', () => {
  assert.equal(SELL_RULE, 'sell-v1');
  assert.deepEqual(Object.keys(SELL_DAYS).sort(), [...S36].sort());
  const c = {}; for (const n of Object.values(SELL_DAYS)) c[n] = (c[n] ?? 0) + 1;
  assert.deepEqual(c, {3: 3, 4: 14, 5: 5, 6: 7, 7: 4, 8: 2, 9: 1});
  assert.equal(SELL_DAYS.g09, 7);
  for (const k of ['g08', 'g13', 'g19', 'g29', 'g32', 'g33']) assert.equal(SELL_DAYS[k], 4, k + ' 기록 모자람 → 아무렇게나 고른 회사의 4일째');
});

test('sellsOf — 꾀가 산 셈만 · 꾀 아닌 묶음은 null · 장날은 장부 값 날 ∪ 하루 몫 날 · 실제 보기 셋(오른 것 · 내린 것 · 88원 줄)', () => {
  const g01 = KINDS.indexOf('g01'), g05 = KINDS.indexOf('g05'), top3 = KINDS.indexOf('top3');
  const B = {px: {
    '000001': {'2026-11-12': 10000, '2026-11-13': 10200, '2026-11-16': 10400, '2026-11-17': 10600, '2026-11-18': 10800},
    '000002': {'2026-11-12': 20000, '2026-11-13': 19800, '2026-11-16': 19500, '2026-11-17': 19000},
    '000003': {'2026-11-12': 5000, '2026-11-13': 4300}},
    mk: {'2026-11-12': 1, '2026-11-13': 1.01, '2026-11-16': 0.99, '2026-11-17': 1, '2026-11-18': 1}};
  const buys = [['2026-11-12', g01, '000001', 10000], ['2026-11-12', g05, '000002', 20000], ['2026-11-12', g01, '000003', 5000], ['2026-11-12', top3, '000001', 10000]];
  const r = sellsOf(B, buys, '2026-11-18', '2026-11-12');
  assert.deepEqual(r.s[0], ['d', '2026-11-18', 10800, 4]); // g01 = 4일째
  assert.deepEqual(r.s[1], ['d', '2026-11-17', 19000, 3]); // g05 = 3일째 · 안 올랐어도 팖
  assert.deepEqual(r.s[2], ['c', '2026-11-13', 4300, 1]); // 5,000원 → 4,400원 줄 · 4,300원 마감 → 그날 팖
  assert.equal(r.s[3], null); // 꾀 아닌 묶음
  assert.deepEqual(r.ex.map(e => [e.kind, e.i]), [['up', 0], ['flat', 1], ['cut', 2]]);
  assert.deepEqual(r.ex[2].ser, [['2026-11-12', 5000], ['2026-11-13', 4300]]);
  assert.equal(r.cut, 88); assert.equal(r.days.g16, 9);
});

test('날마다 사고 팔기 셈 모두(sell.tt · 주문 1125-2248 한눈에 수익률 추이) — 그날까지 산 것의 산 돈 · 값(판 것 = 판 값 · 들고 있음 = 그날 종가) · 꾀 아닌 묶음 밖 · 끝 날 = 모두 합', () => {
  const g05 = KINDS.indexOf('g05'), top = KINDS.indexOf('top3'); // g05 = 3일째에 팖
  const B = {px: {A00001: {'2026-11-12': 1000, '2026-11-13': 1100, '2026-11-16': 900, '2026-11-17': 1200, '2026-11-18': 1300}, B00002: {'2026-11-13': 2000, '2026-11-16': 2100, '2026-11-17': 1900, '2026-11-18': 2200}}, mk: {}};
  const buys = [['2026-11-12', g05, 'A00001', 1000], ['2026-11-13', g05, 'B00002', 2000], ['2026-11-12', top, 'A00001', 1000]];
  const S = sellsOf(B, buys, '2026-11-18', '2026-11-12');
  assert.deepEqual(S.s[0], ['d', '2026-11-17', 1200, 3]); assert.equal(S.s[2], null);
  assert.deepEqual(S.tt.days, ['2026-11-12', '2026-11-13', '2026-11-16', '2026-11-17', '2026-11-18']);
  assert.deepEqual(S.tt.c, [10000, 30000, 30000, 30000, 30000]);
  assert.deepEqual(S.tt.v, [10000, 31000, 30000, 31000, 34000]); // 11-17: A 판 값 1200 + B 1900 · 11-18: A 판 값 그대로 1200 + B 2200
});

test('꾀마다 날마다(sell.tk · 주문 1127-1412 꾀별 꺾은선) — tt 와 같은 날 · 꾀마다 산 돈 · 값 · 산 셈 없는 날은 null · 꾀를 모두 더하면 tt', () => {
  const g01 = KINDS.indexOf('g01'), g05 = KINDS.indexOf('g05'), top = KINDS.indexOf('top3');
  const B = {px: {A00001: {'2026-11-12': 1000, '2026-11-13': 1100, '2026-11-16': 900, '2026-11-17': 1200, '2026-11-18': 1300}, B00002: {'2026-11-13': 2000, '2026-11-16': 2100, '2026-11-17': 1900, '2026-11-18': 2200}}, mk: {}};
  const buys = [['2026-11-12', g05, 'A00001', 1000], ['2026-11-13', g01, 'B00002', 2000], ['2026-11-12', top, 'A00001', 1000]];
  const S = sellsOf(B, buys, '2026-11-18', '2026-11-12'), j1 = S36.indexOf('g01'), j5 = S36.indexOf('g05');
  assert.deepEqual(S.tk.k, [...S36]); assert.equal(S.tk.c.length, 36); assert.ok(S.tk.c.every(a => a.length === S.tt.days.length));
  assert.deepEqual(S.tk.c[j5], [10000, 10000, 10000, 10000, 10000]);
  assert.deepEqual(S.tk.v[j5], [10000, 11000, 9000, 12000, 12000]); // 11-17 3일째에 판 값 1200 · 그 뒤 그대로
  assert.deepEqual(S.tk.c[j1], [null, 20000, 20000, 20000, 20000]); // 11-12 에는 g01 산 셈 없음
  assert.deepEqual(S.tk.v[j1], [null, 20000, 21000, 19000, 22000]);
  assert.ok(S.tk.c.every((a, j) => j === j1 || j === j5 || a.every(x => x === null)));
  S.tt.days.forEach((d, i) => { const sum = f => S.tk[f].reduce((a, x) => a + (x[i] ?? 0), 0); assert.equal(sum('c'), S.tt.c[i], d); assert.equal(sum('v'), S.tt.v[i], d); });
});
